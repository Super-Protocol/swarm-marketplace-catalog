#!/usr/bin/env python3
"""Port the blueprint's notebooks for a confidential deployment.

`charts/rapids-singlecell-notebook/files/notebooks/0{1,2,3}_*.ipynb` are
generated by this script and should not be edited by hand — a hand edit is a
modification of somebody else's Apache-2.0 work that `PROVENANCE.md` does not
describe, which is the one thing that notice exists to prevent.

    git clone --depth 1 https://github.com/NVIDIA-AI-Blueprints/single-cell-analysis-blueprint
    scripts/port-single-cell-notebooks.py \
        single-cell-analysis-blueprint/notebooks \
        charts/rapids-singlecell-notebook/files/notebooks

Four edits, listed in PROVENANCE.md and marked `# Ported:` in every cell they
touch: the download of a public corpus becomes `sc_workspace.load_matrix()`,
the two hard-coded `obs` column names become this deployment's parameters, the
`feature_name` reindex is guarded, and derived files are written to the volume
rather than to a working directory the pod throws away. Stored outputs are
stripped — 11 MB of images computed from a corpus no deployment of this listing
has, which would otherwise be published inside its evidence snapshot.

`00_dataset.ipynb` is ours and is not generated here.

The cell indices below are the upstream notebooks' at commit
7c4148c59049563554708e01c378352586ab2f4a. Re-run this against a newer upstream
and CHECK THEM: the script asserts nothing about what it is replacing, so a cell
that moved would be silently rewritten into the wrong place.
"""
import json
import pathlib
import re
import sys

UPSTREAM = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)

HEADER = (
    "> **Ported for confidential execution.** This is NVIDIA's "
    "[Single-Cell Analysis Blueprint]"
    "(https://github.com/NVIDIA-AI-Blueprints/single-cell-analysis-blueprint) notebook, "
    "Apache-2.0, with its download step replaced by `sc_workspace.load_matrix()` and its "
    "hard-coded `obs` column names replaced by this deployment's own. Nothing else is changed. "
    "`PROVENANCE.md` lists every edit.\n"
)

LOADER = """# Ported: upstream downloaded a public example corpus from
# exampledata.scverse.org here. This deployment reads the matrix the operator
# bound to it — a marketplace dataset, or a file uploaded into /workspace/data —
# and nothing in this notebook reaches the network.
import sc_workspace as scw

print(scw.describe_binding())
adata = scw.load_matrix()

# Which column is the batch, and which carries an annotation. Asked now, with
# the column list in the error, rather than forty cells later inside Harmony.
batch = scw.batch_key(adata)
label = scw.label_key(adata)
print(f"batch column: {batch!r}; annotation column: {label!r}; {adata.n_obs} cells x {adata.n_vars} genes")

# The batch column is required and raised above if it was wrong. The annotation
# is not required by the workflow — but every cell that compares this notebook's
# own clustering against a known cell type needs it, and without it they fail on
# a bare KeyError from scanpy a long way below. Said here instead.
if label is None:
    print(
        f"\nNOTE: no annotation column. This deployment names {scw.LABEL_KEY!r} and the matrix\n"
        f"      has none of it. Everything up to the clustering runs; the cells that colour or\n"
        f"      group by the annotation will raise KeyError({scw.LABEL_KEY!r}).\n"
        f"      Available: {', '.join(map(str, adata.obs.columns))}\n"
        f"      Fix it by reconfiguring the deployment, or set scw.LABEL_KEY here."
    )
"""

NETWORK_NOTE = """> **This notebook reaches the network, and it is the only one that does.**
> The next cell calls `decoupler.op.collectri()`, which downloads the CollecTRI
> regulon table from Zenodo (~6 MB of public reference data: transcription
> factors and their targets). **No data of yours leaves the deployment** — the
> request carries nothing but a GET — but it does mean this notebook needs
> outbound HTTPS, and that the table is not covered by the attested
> `requirements.lock`, so it is whatever Zenodo serves that day.
>
> In a deployment with no egress the call fails. Two ways round it: upload the
> CSV into `/workspace/data` yourself and read it with `pandas.read_csv`
> (`decoupler` takes any frame with `source`, `target` and `weight` columns), or
> leave this notebook for a deployment that is allowed out. `01_preprocessing`
> and `03_pearson_residuals` touch nothing outside the workspace.
"""

ALREADY_LOADED = """# Ported: the matrix is already in memory — the cell above read it from the
# dataset this deployment is bound to. Upstream re-read the file it had just
# downloaded.
adata
"""

VAR_NAMES_GUARD = """# Ported: guarded. `feature_name` is a column of the corpus upstream downloads;
# a tenant's own matrix is already indexed by gene name more often than not.
if "feature_name" in adata.var:
    adata.var_names = adata.var.feature_name.astype(str).to_numpy()
"""


def strip(notebook: dict) -> dict:
    for cell in notebook["cells"]:
        if cell["cell_type"] == "code":
            cell["outputs"] = []
            cell["execution_count"] = None
        cell.pop("id", None)
    return notebook


def keys(source: str) -> str:
    """The two column names the upstream notebooks hard-code."""
    source = re.sub(r'(["\'])assay\1', "scw.BATCH_KEY", source)
    source = re.sub(r'(["\'])cell_type\1', "scw.LABEL_KEY", source)
    return source


def cell(kind: str, source: str) -> dict:
    lines = source.splitlines(keepends=True)
    if kind == "code":
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": lines}
    return {"cell_type": "markdown", "metadata": {}, "source": lines}


def set_source(notebook: dict, index: int, source: str) -> None:
    notebook["cells"][index]["source"] = source.splitlines(keepends=True)


def write(notebook: dict, name: str) -> None:
    notebook["cells"].insert(0, cell("markdown", HEADER))
    # nbformat 4.5 wants an id per cell and warns on every execution without one
    # ("will become a hard error"). Positional and therefore deterministic: a
    # random id would change the ConfigMap, and the attested snapshot with it,
    # every time these were regenerated.
    for index, c in enumerate(notebook["cells"]):
        c["id"] = f"sc{index:03d}"
    notebook["nbformat_minor"] = max(notebook.get("nbformat_minor", 5), 5)
    (OUT / name).write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n")
    print(f"  {name}: {len(notebook['cells'])} cells")


# --- 01: preprocessing -----------------------------------------------------
nb = strip(json.loads((UPSTREAM / "01_scRNA_analysis_preprocessing.ipynb").read_text()))
set_source(nb, 5, LOADER)
set_source(nb, 8, ALREADY_LOADED)
set_source(nb, 13, VAR_NAMES_GUARD)
for index, c in enumerate(nb["cells"]):
    if c["cell_type"] == "code" and index not in (5, 8, 13):
        set_source(nb, index, keys("".join(c["source"])))
set_source(
    nb,
    86,
    '# Ported: upstream wrote h5/dli_decoupler.h5ad next to the downloaded corpus.\n'
    '# /workspace/derived is the volume that survives a restart, and is where\n'
    '# 02_regulatory_activity.ipynb reads this file from.\n'
    'adata.write(scw.derived("preprocessed.h5ad"))\n',
)
set_source(
    nb,
    87,
    "## Next steps\n\n"
    "The preprocessed matrix is now at `/workspace/derived/preprocessed.h5ad`. "
    "**[02_regulatory_activity.ipynb](02_regulatory_activity.ipynb)** picks it up from there.\n",
)
write(nb, "01_preprocessing.ipynb")

# --- 02: decoupler ---------------------------------------------------------
nb = strip(json.loads((UPSTREAM / "02_scRNA_analysis_extended.ipynb").read_text()))
set_source(
    nb,
    2,
    "# Ported: upstream read ./h5/dli_decoupler.h5ad, written beside the corpus it\n"
    "# had downloaded. 01_preprocessing.ipynb writes the same matrix to the\n"
    "# workspace volume instead.\n"
    "import sc_workspace as scw\n\n"
    'adata = scw.load_matrix(path=scw.derived("preprocessed.h5ad"))\n'
    "adata\n",
)
for index, c in enumerate(nb["cells"]):
    if c["cell_type"] == "code" and index != 2:
        set_source(nb, index, keys("".join(c["source"])))
# The one network call left anywhere in these notebooks, marked immediately
# above the cell that makes it rather than in a README nobody opens next to the
# traceback. Located rather than indexed, so it stays correct if upstream moves.
network = next(
    index for index, c in enumerate(nb["cells"])
    if c["cell_type"] == "code" and "dc.op.collectri(" in "".join(c["source"])
)
nb["cells"].insert(network, cell("markdown", NETWORK_NOTE))
write(nb, "02_regulatory_activity.ipynb")

# --- 03: Pearson residuals -------------------------------------------------
nb = strip(json.loads((UPSTREAM / "03_scRNA_analysis_with_pearson_residuals.ipynb").read_text()))
set_source(nb, 5, LOADER)
set_source(nb, 8, ALREADY_LOADED)
set_source(
    nb,
    13,
    "# Ported: guarded, as in 01_preprocessing.ipynb.\n"
    'if "feature_name" in adata.var:\n'
    "    adata.var_names = adata.var.feature_name\n",
)
for index, c in enumerate(nb["cells"]):
    if c["cell_type"] == "code" and index not in (5, 8, 13):
        set_source(nb, index, keys("".join(c["source"])))
write(nb, "03_pearson_residuals.ipynb")
