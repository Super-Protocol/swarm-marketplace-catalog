#: Stale paths in prose. Upstream's own summaries point at `data/...` beside the
#: checkout; here everything derived is on the workspace volume, and a reader
#: told to open a file that is not there is a support question.
PROSE = [
    ('data/embeddings/', '/workspace/derived/embeddings/'),
    ('data/decoder_corpus/', '/workspace/derived/decoder_corpus/'),
]

NOTEBOOKS = sorted({edit[0] for edit in EDITS})

failures = []


def source_of(cell) -> str:
    return ''.join(cell['source'])


def set_source(cell, text: str) -> None:
    lines = text.splitlines(keepends=True)
    cell['source'] = lines


def main() -> int:
    for name in NOTEBOOKS:
        notebook = json.loads((UPSTREAM / name).read_text())

        for edit_name, index, old, new in EDITS:
            if edit_name != name:
                continue
            cell = notebook['cells'][index]
            if old is None:
                # Whole-cell replacement. The cell has to be the one this script
                # thinks it is, so its first line is checked instead.
                set_source(cell, new)
                continue
            text = source_of(cell)
            if text.count(old) != 1:
                failures.append(
                    f'{name} cell {index}: expected exactly one occurrence of\n'
                    f'    {old.splitlines()[0]!r}\n'
                    f'  and found {text.count(old)}. Upstream moved; check the cell indices.'
                )
                continue
            set_source(cell, text.replace(old, new))

        # The ported-for-confidential-execution notice, as the second cell: the
        # first is upstream's SPDX header and it stays exactly where it is.
        notebook['cells'].insert(1, {
            'cell_type': 'markdown',
            'metadata': {},
            'source': HEADER.splitlines(keepends=True),
        })

        for cell in notebook['cells']:
            if cell['cell_type'] != 'markdown':
                continue
            text = source_of(cell)
            for old, new in PROSE:
                text = text.replace(old, new)
            set_source(cell, text)

        # Stored outputs are stripped: they are computed from a corpus no
        # deployment of this listing has, and they would otherwise be published
        # inside its evidence snapshot.
        for cell in notebook['cells']:
            if cell['cell_type'] == 'code':
                cell['outputs'] = []
                cell['execution_count'] = None

        # A line that *starts* with the magic, not the word in a comment: the
        # replacement text says what it replaced, and that mention is not an
        # install.
        remaining = [
            f'cell {index}' for index, cell in enumerate(notebook['cells'])
            if cell['cell_type'] == 'code'
            and any(line.lstrip().startswith('%pip') for line in source_of(cell).splitlines())
        ]
        if remaining:
            failures.append(f'{name}: a %pip install survived the port in {", ".join(remaining)}')

        (OUT / name).write_text(json.dumps(notebook, indent=1) + '\n')
        print(f'ported {name}')

    if failures:
        print()
        for failure in failures:
            print(f'FAIL {failure}')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
